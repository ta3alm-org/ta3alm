class RefactorContractsTests(TestCase):
    def setUp(self):
        cache.clear()

    def tearDown(self):
        cache.clear()

    def test_url_contracts(self):
        for item in URL_CONTRACTS:
            if item['args'] is not None:
                path = reverse(item['name'], args=item['args'])
            elif item['kwargs']:
                path = reverse(item['name'], kwargs=item['kwargs'])
            else:
                path = reverse(item['name'])
            self.assertEqual(path, item['path'], f"URL mismatch for {item['name']}")
            match = resolve(path)
            cb_name = getattr(match.func, '__name__', repr(match.func))
            self.assertEqual(cb_name, item['resolved_callback'], f"Callback mismatch for {path}")

    def test_import_compatibility(self):
        for mod_name, expected_names in IMPORT_SURFACE_CONTRACTS.items():
            mod = importlib.import_module(mod_name)
            for attr in expected_names:
                self.assertTrue(hasattr(mod, attr), f"Missing {attr} in {mod_name}")

    def test_signal_receiver_counts(self):
        model_id_to_label = {id(m): m._meta.label for m in apps.get_models()}
        sig_map = {
            'pre_save': pre_save,
            'post_save': post_save,
            'pre_delete': pre_delete,
            'post_delete': post_delete,
            'm2m_changed': m2m_changed,
            'user_logged_in': user_logged_in,
            'user_logged_out': user_logged_out,
            'user_login_failed': user_login_failed,
        }
        actual = {}
        for sig_name, sig in sig_map.items():
            counts = {}
            for lookup_key, receiver_ref, *_ in sig.receivers:
                fn = receiver_ref() if isinstance(receiver_ref, weakref.ReferenceType) else receiver_ref
                if fn is None:
                    continue
                sender_id = lookup_key[1] if isinstance(lookup_key, tuple) and len(lookup_key) > 1 else None
                sender_lbl = (
                    '__None__'
                    if sender_id is None
                    else model_id_to_label.get(sender_id, f'other:{type(sender_id).__name__}')
                )
                counts[sender_lbl] = counts.get(sender_lbl, 0) + 1
            actual[sig_name] = counts
        self.assertEqual(actual, SIGNAL_COUNT_CONTRACTS)

